/* ── GET /api/agri-services/:id — Single detail ── */
router.get('/:id', async (req, res) => {
  try {
    const db = getDb();
    await ensureAgriTable(db);
    const listing = await db.prepare(`
      SELECT s.*, u.username as provider_name, u.phone as provider_phone, u.bio as provider_bio
      FROM agri_service_listings s
      JOIN users u ON s.provider_id = u.id
      WHERE s.id = ?
    `).get(req.params.id);

    if (!listing) return res.status(404).json({ error: 'Service listing not found.' });

    const stats = await db.prepare(`
      SELECT COALESCE(AVG(rating), 0) as avg_rating, COUNT(*) as total_reviews
      FROM reviews WHERE reviewee_id = ?
    `).get(listing.provider_id);

    listing.avg_rating = Math.round((stats?.avg_rating || 5) * 10) / 10;
    listing.total_reviews = stats?.total_reviews || 0;

    res.json({ listing });
  } catch (err) {
    res.status(500).json({ error: 'Server error.' });
  }
});

/* ── POST /api/agri-services — Create Listing ── */
router.post('/', authenticateToken, async (req, res) => {
  try {
    const db = getDb();
    await ensureAgriTable(db);

    const {
      title, category, sub_category, description, price, pricing_type,
      equipment_included, service_area_km, location, district, state,
      lat, lng, photo_url
    } = req.body;

    if (!title || !category || !price || !location) {
      return res.status(400).json({ error: 'Title, category, price, and location are required.' });
    }

    const result = await db.prepare(`
      INSERT INTO agri_service_listings (
        provider_id, title, category, sub_category, description, price, pricing_type,
        equipment_included, service_area_km, location, district, state, lat, lng,
        photo_url, status
      ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 'approved')
    `).run(
      req.user.id,
      title,
      category,
      sub_category || null,
      description || null,
      Number(price),
      pricing_type || 'per_acre',
      equipment_included || null,
      service_area_km ? Number(service_area_km) : 25,
      location,
      district || null,
      state || null,
      lat ? Number(lat) : null,
      lng ? Number(lng) : null,
      photo_url || null
    );

    const listing = await db.prepare('SELECT * FROM agri_service_listings WHERE id = ?').get(result.lastInsertRowid);
    res.status(201).json({ message: 'Agricultural service listing created successfully!', listing });
  } catch (err) {
    console.error('Create agri service error:', err);
    res.status(500).json({ error: 'Server error creating service listing.' });
  }
});

/* ── PUT /api/agri-services/:id — Update ── */
router.put('/:id', authenticateToken, async (req, res) => {
  try {
    const db = getDb();
    await ensureAgriTable(db);

    const listing = await db.prepare('SELECT * FROM agri_service_listings WHERE id = ?').get(req.params.id);
    if (!listing) return res.status(404).json({ error: 'Listing not found.' });

    if (listing.provider_id !== req.user.id && req.user.role !== 'admin') {
      return res.status(403).json({ error: 'Not authorized to update this listing.' });
    }

    const {
      title, category, sub_category, description, price, pricing_type,
      equipment_included, service_area_km, location, district, state,
      availability, status, photo_url
    } = req.body;

    await db.prepare(`
      UPDATE agri_service_listings
      SET title = COALESCE(?, title),
          category = COALESCE(?, category),
          sub_category = COALESCE(?, sub_category),
          description = COALESCE(?, description),
          price = COALESCE(?, price),
          pricing_type = COALESCE(?, pricing_type),
          equipment_included = COALESCE(?, equipment_included),
          service_area_km = COALESCE(?, service_area_km),
          location = COALESCE(?, location),
          district = COALESCE(?, district),
          state = COALESCE(?, state),
          availability = COALESCE(?, availability),
          status = COALESCE(?, status),
          photo_url = COALESCE(?, photo_url),
          updated_at = NOW()
      WHERE id = ?
    `).run(
      title || null, category || null, sub_category || null, description || null,
      price ? Number(price) : null, pricing_type || null, equipment_included || null,
      service_area_km ? Number(service_area_km) : null, location || null,
      district || null, state || null, availability || null, status || null,
      photo_url || null, req.params.id
    );

    const updated = await db.prepare('SELECT * FROM agri_service_listings WHERE id = ?').get(req.params.id);
    res.json({ message: 'Service updated.', listing: updated });
  } catch (err) {
    console.error('Update agri service error:', err);
    res.status(500).json({ error: 'Server error updating service.' });
  }
});

