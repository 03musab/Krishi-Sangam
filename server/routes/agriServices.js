const express = require('express');
const { getDb } = require('../db');
const { authenticateToken, requireRole } = require('../middleware/auth');

const router = express.Router();

/* Ensure table exists */
async function ensureAgriTable(db) {
  await db.exec(`
    CREATE TABLE IF NOT EXISTS agri_service_listings (
      id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      provider_id        BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      title              TEXT NOT NULL,
      category           TEXT NOT NULL,
      sub_category       TEXT,
      description        TEXT,
      price              INTEGER NOT NULL,
      pricing_type       TEXT DEFAULT 'per_acre' CHECK(pricing_type IN ('per_acre','per_hour','per_day','fixed')),
      equipment_included TEXT,
      service_area_km    INTEGER DEFAULT 25,
      location           TEXT NOT NULL,
      district           TEXT,
      state              TEXT,
      lat                DOUBLE PRECISION,
      lng                DOUBLE PRECISION,
      availability       TEXT DEFAULT 'available' CHECK(availability IN ('available','busy','offline')),
      photo_url          TEXT,
      status             TEXT DEFAULT 'approved' CHECK(status IN ('pending','approved','rejected')),
      created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
      updated_at         TIMESTAMPTZ NOT NULL DEFAULT now()
    );

    CREATE INDEX IF NOT EXISTS idx_agri_service_provider ON agri_service_listings(provider_id);
    CREATE INDEX IF NOT EXISTS idx_agri_service_category ON agri_service_listings(category);
    CREATE INDEX IF NOT EXISTS idx_agri_service_status ON agri_service_listings(status);
  `);
}

/* ── GET /api/agri-services — List all approved services ── */
router.get('/', async (req, res) => {
  try {
    const db = getDb();
    await ensureAgriTable(db);

    const { search, category, district, state, pricing_type, min_price, max_price } = req.query;

    let query = `
      SELECT s.*, u.username as provider_name, u.phone as provider_phone, u.avatar_url as provider_avatar
      FROM agri_service_listings s
      JOIN users u ON s.provider_id = u.id
      WHERE s.status = 'approved'
    `;
    const params = [];

    if (search) {
      query += ` AND (s.title ILIKE ? OR s.category ILIKE ? OR s.description ILIKE ? OR s.location ILIKE ? OR s.equipment_included ILIKE ?)`;
      params.push(`%${search}%`, `%${search}%`, `%${search}%`, `%${search}%`, `%${search}%`);
    }
    if (category && category !== 'All') {
      query += ` AND s.category ILIKE ?`;
      params.push(`%${category}%`);
    }
    if (district) {
      query += ` AND s.district ILIKE ?`;
      params.push(`%${district}%`);
    }
    if (state) {
      query += ` AND s.state ILIKE ?`;
      params.push(`%${state}%`);
    }
    if (pricing_type) {
      query += ` AND s.pricing_type = ?`;
      params.push(pricing_type);
    }
    if (min_price) {
      query += ` AND s.price >= ?`;
      params.push(Number(min_price));
    }
    if (max_price) {
      query += ` AND s.price <= ?`;
      params.push(Number(max_price));
    }

    query += ` ORDER BY s.created_at DESC`;
    const listings = await db.prepare(query).all(...params);

    // Fetch review ratings stats per provider
    for (const item of listings) {
      const stats = await db.prepare(`
        SELECT COALESCE(AVG(rating), 0) as avg_rating, COUNT(*) as total_reviews
        FROM reviews
        WHERE reviewee_id = ?
      `).get(item.provider_id);
      item.avg_rating = Math.round((stats?.avg_rating || 5) * 10) / 10;
      item.total_reviews = stats?.total_reviews || 0;
    }

    res.json({ listings, count: listings.length });
  } catch (err) {
    console.error('Get agri services error:', err);
    res.status(500).json({ error: 'Server error fetching agricultural services.' });
  }
});

